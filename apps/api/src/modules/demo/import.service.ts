export const IMPORT_SOURCES = {
  dummyjson: {
    label: "DummyJSON (public demo API)",
    url: "https://dummyjson.com",
    license:
      "DummyJSON returns fictional placeholder data intended for testing and prototyping; see https://dummyjson.com/docs and https://github.com/Ovi/DummyJSON for terms.",
    isSynthetic: false,
  },
  fleqo_synthetic: {
    label: "Fleqo synthetic generator (offline)",
    url: null,
    license: "Generated by Fleqo. Entirely synthetic; contains no real personal data.",
    isSynthetic: true,
  },
} as const;

export type ImportSource = keyof typeof IMPORT_SOURCES;

export interface NormalizedCustomer {
  externalId: string;
  name: string;
  email: string;
}
export interface NormalizedProduct {
  sku: string;
  name: string;
  unitPriceMinor: number;
  currency: "USD";
  category: string | null;
}
export interface NormalizedCart {
  externalId: string;
  customerExternalId: string;
  items: { sku: string; name: string; quantity: number; unitPriceMinor: number }[];
}

interface ImportRow {
  sourceRecordId: string;
  kind: "customer" | "product" | "cart";
  data: NormalizedCustomer | NormalizedProduct | NormalizedCart;
  raw: Prisma.InputJsonValue | null;
}

const toMinor = (amount: number) => Math.round(amount * 100);

// ── DummyJSON adapter ─────────────────────────────────────────────────────
const djUsers = z.object({
  users: z.array(z.object({ id: z.number().int(), firstName: z.string(), lastName: z.string(), email: z.email() })),
});
const djProducts = z.object({
  products: z.array(
    z.object({
      id: z.number().int(),
      title: z.string().min(1),
      price: z.number().nonnegative(),
      category: z.string().optional(),
      sku: z.string().optional(),
    }),
  ),
});
const djCarts = z.object({
  carts: z.array(
    z.object({
      id: z.number().int(),
      userId: z.number().int(),
      products: z.array(
        z.object({ id: z.number().int(), title: z.string(), price: z.number().nonnegative(), quantity: z.number().int().min(1) }),
      ),
    }),
  ),
});

export type FetchJson = (url: string) => Promise<unknown>;

const defaultFetchJson: FetchJson = async (url) => {
  const response = await fetch(url, { signal: AbortSignal.timeout(10_000), headers: { Accept: "application/json" } });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  return response.json();
};

const productSku = (id: number) => `dj_product_${id}`;

/** Fetches from fixed DummyJSON endpoints only; no user-supplied URLs are ever requested. */
export async function fetchDummyJson(limit: number, fetchJson: FetchJson = defaultFetchJson): Promise<ImportRow[]> {
  const base = IMPORT_SOURCES.dummyjson.url;
  let users, products, carts;
  try {
    [users, products, carts] = await Promise.all([
      fetchJson(`${base}/users?limit=${limit}&select=firstName,lastName,email`).then((json) => djUsers.parse(json)),
      fetchJson(`${base}/products?limit=${limit}&select=title,price,category,sku`).then((json) => djProducts.parse(json)),
      fetchJson(`${base}/carts?limit=${Math.min(limit, 20)}`).then((json) => djCarts.parse(json)),
    ]);
  } catch (error) {
    const reason = error instanceof z.ZodError ? "unexpected response shape" : (error as Error).message;
    throw new AppError("service_unavailable", `DummyJSON import failed (${reason}). Try the offline synthetic source.`);
  }

  return [
    ...users.users.map((user) => ({
      sourceRecordId: `users/${user.id}`,
      kind: "customer" as const,
      data: { externalId: `dj_user_${user.id}`, name: `${user.firstName} ${user.lastName}`, email: user.email.toLowerCase() },
      raw: user,
    })),
    ...products.products.map((product) => ({
      sourceRecordId: `products/${product.id}`,
      kind: "product" as const,
      data: {
        sku: productSku(product.id),
        name: product.title,
        unitPriceMinor: toMinor(product.price),
        currency: "USD" as const,
        category: product.category ?? null,
      },
      raw: product,
    })),
    ...carts.carts.map((cart) => ({
      sourceRecordId: `carts/${cart.id}`,
      kind: "cart" as const,
      data: {
        externalId: `dj_cart_${cart.id}`,
        customerExternalId: `dj_user_${cart.userId}`,
        items: cart.products.map((item) => ({
          sku: productSku(item.id),
          name: item.title,
          quantity: item.quantity,
          unitPriceMinor: toMinor(item.price),
        })),
      },
      raw: { id: cart.id, userId: cart.userId, productCount: cart.products.length },
    })),
  ];
}

// ── Offline synthetic generator (deterministic) ──────────────────────────────
function mulberry32(seed: number) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

