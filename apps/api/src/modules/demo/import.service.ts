export function generateSynthetic(limit: number, seed = 20261031): ImportRow[] {
  const random = mulberry32(seed);
  const pick = <T>(list: T[]) => list[Math.floor(random() * list.length)];
  const rows: ImportRow[] = [];

  for (let i = 1; i <= limit; i++) {
    const first = pick(FIRST);
    const last = pick(LAST);
    rows.push({
      sourceRecordId: `customers/${i}`,
      kind: "customer",
      data: {
        externalId: `syn_customer_${String(i).padStart(3, "0")}`,
        name: `${first} ${last}`,
        email: `${first}.${last}.${i}@example.test`.toLowerCase(),
      },
      raw: null,
    });
  }
  PRODUCTS.slice(0, Math.max(1, Math.min(limit, PRODUCTS.length))).forEach(([name, price, category], index) => {
    rows.push({
      sourceRecordId: `products/${index + 1}`,
      kind: "product",
      data: { sku: `syn_sku_${index + 1}`, name, unitPriceMinor: price, currency: "USD", category },
      raw: null,
    });
  });
  return rows;
}

// ── Persistence ─────────────────────────────────────────────────────────────
export async function runImport(params: {
  organizationId: string;
  actorUserId: string | null;
  source: ImportSource;
  limit: number;
  fetchJson?: FetchJson;
}) {
  const { organizationId, source, limit } = params;
  const info = IMPORT_SOURCES[source];
  const rows = source === "dummyjson" ? await fetchDummyJson(limit, params.fetchJson) : generateSynthetic(limit);

  const existing = await prisma.importedRecord.findMany({
    where: { organizationId, source, sourceRecordId: { in: rows.map((row) => row.sourceRecordId) } },
    select: { sourceRecordId: true },
  });
  const existingIds = new Set(existing.map((record) => record.sourceRecordId));

  await prisma.$transaction(
    async (tx) => {
      for (const row of rows) {
        const values = {
          kind: row.kind,
          data: row.data as unknown as Prisma.InputJsonValue,
          raw: row.raw ?? undefined,
          isSynthetic: info.isSynthetic,
          sourceUrl: info.url,
          license: info.license,
          importedById: params.actorUserId,
        };
        await tx.importedRecord.upsert({
          where: { organizationId_source_sourceRecordId: { organizationId, source, sourceRecordId: row.sourceRecordId } },
          create: { organizationId, source, sourceRecordId: row.sourceRecordId, ...values },
          update: values,
        });
      }
      await recordAudit(tx, {
        organizationId,
        actorUserId: params.actorUserId,
        action: "demo.imported",
        targetType: "imported_record",
        metadata: { source, fetched: rows.length },
      });
    },
    { timeout: 30_000 },
  );

  const byKind = rows.reduce<Record<string, number>>((acc, row) => ({ ...acc, [row.kind]: (acc[row.kind] ?? 0) + 1 }), {});
  return {
    source,
    label: info.label,
    license: info.license,
    isSynthetic: info.isSynthetic,
    fetched: rows.length,
    created: rows.filter((row) => !existingIds.has(row.sourceRecordId)).length,
    updated: rows.filter((row) => existingIds.has(row.sourceRecordId)).length,
    byKind,
  };
}
